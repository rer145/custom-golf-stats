#:property PublishAot=false
// Generates src/CustomGolfStats.App/Themes/BrandTokens.xaml from brand/tokens/tokens.json.
// Run from the repository root:  dotnet run tools/generate-uno-theme.cs
// CI runs it and fails if the committed file differs (the tokens are the source of truth; never edit the XAML by hand).
using System.Globalization;
using System.Text;
using System.Text.Json;

var root = args.Length > 0 ? args[0] : Directory.GetCurrentDirectory();
var tokensPath = Path.Combine(root, "brand", "tokens", "tokens.json");
var outPath = Path.Combine(root, "src", "CustomGolfStats.App", "Themes", "BrandTokens.xaml");

using var doc = JsonDocument.Parse(File.ReadAllText(tokensPath));
var t = doc.RootElement;
var inv = CultureInfo.InvariantCulture;
var sb = new StringBuilder();

string Pascal(string key) => key.Length == 0 ? key : char.ToUpperInvariant(key[0]) + key[1..];
string Num(double v) => v.ToString("0.###", inv);
string Argb(string hex) => "#FF" + hex.TrimStart('#').ToUpperInvariant();

sb.AppendLine("<!-- GENERATED by tools/generate-uno-theme.cs from brand/tokens/tokens.json. Do not edit by hand. -->");
sb.AppendLine("<ResourceDictionary xmlns=\"http://schemas.microsoft.com/winfx/2006/xaml/presentation\"");
sb.AppendLine("                    xmlns:x=\"http://schemas.microsoft.com/winfx/2006/xaml\">");
sb.AppendLine();

// Semantic colours per theme: Brand<Name>Color and Brand<Name>Brush.
sb.AppendLine("  <ResourceDictionary.ThemeDictionaries>");
foreach (var (theme, key) in new[] { ("Light", "light"), ("Dark", "dark") })
{
    sb.AppendLine($"    <ResourceDictionary x:Key=\"{theme}\">");
    foreach (var c in t.GetProperty("color").GetProperty(key).EnumerateObject())
        sb.AppendLine($"      <Color x:Key=\"Brand{Pascal(c.Name)}Color\">{Argb(c.Value.GetString()!)}</Color>");
    foreach (var c in t.GetProperty("color").GetProperty(key).EnumerateObject())
        sb.AppendLine($"      <SolidColorBrush x:Key=\"Brand{Pascal(c.Name)}Brush\" Color=\"{Argb(c.Value.GetString()!)}\" />");
    sb.AppendLine("    </ResourceDictionary>");
}
sb.AppendLine("  </ResourceDictionary.ThemeDictionaries>");
sb.AppendLine();

// Raw brand palette (same in both themes): BrandPalette<Name>Color / Brush.
sb.AppendLine("  <!-- Brand palette (theme independent). Prefer the semantic theme resources above. -->");
foreach (var c in t.GetProperty("color").GetProperty("brand").EnumerateObject())
{
    sb.AppendLine($"  <Color x:Key=\"BrandPalette{Pascal(c.Name)}Color\">{Argb(c.Value.GetString()!)}</Color>");
    sb.AppendLine($"  <SolidColorBrush x:Key=\"BrandPalette{Pascal(c.Name)}Brush\" Color=\"{Argb(c.Value.GetString()!)}\" />");
}
sb.AppendLine();

// Fonts: one family resource per bundled file, named after tokens font.nativeFiles.
var families = t.GetProperty("font").GetProperty("family");
sb.AppendLine("  <!-- Fonts (static TTFs from brand/fonts, bundled under Assets/Fonts). Select the weight by family, never by FontWeight. -->");
foreach (var f in t.GetProperty("font").GetProperty("nativeFiles").EnumerateObject())
{
    var group = f.Name.StartsWith("display") ? "display" : f.Name.StartsWith("mono") ? "mono" : "body";
    sb.AppendLine($"  <FontFamily x:Key=\"BrandFont{Pascal(f.Name)}\">ms-appx:///Assets/Fonts/{f.Value.GetString()}.ttf#{families.GetProperty(group).GetString()}</FontFamily>");
}
sb.AppendLine();

sb.AppendLine("  <!-- Font sizes -->");
foreach (var s in t.GetProperty("font").GetProperty("size").EnumerateObject())
    sb.AppendLine($"  <x:Double x:Key=\"BrandFontSize{Pascal(s.Name)}\">{Num(s.Value.GetDouble())}</x:Double>");
sb.AppendLine();

sb.AppendLine("  <!-- Spacing (4 px scale): BrandSpaceN as a double, BrandPaddingN as a uniform Thickness -->");
foreach (var s in t.GetProperty("space").EnumerateObject())
{
    sb.AppendLine($"  <x:Double x:Key=\"BrandSpace{s.Name}\">{Num(s.Value.GetDouble())}</x:Double>");
    sb.AppendLine($"  <Thickness x:Key=\"BrandPadding{s.Name}\">{Num(s.Value.GetDouble())}</Thickness>");
}
sb.AppendLine();

sb.AppendLine("  <!-- Corner radii -->");
foreach (var r in t.GetProperty("radius").EnumerateObject())
    sb.AppendLine($"  <CornerRadius x:Key=\"BrandRadius{Pascal(r.Name)}\">{Num(r.Value.GetDouble())}</CornerRadius>");
sb.AppendLine();

sb.AppendLine("  <!-- Sizes -->");
foreach (var s in t.GetProperty("size").EnumerateObject())
    sb.AppendLine($"  <x:Double x:Key=\"Brand{Pascal(s.Name)}\">{Num(s.Value.GetDouble())}</x:Double>");
sb.AppendLine($"  <Thickness x:Key=\"BrandBorderThickness\">{Num(t.GetProperty("border").GetProperty("width").GetDouble())}</Thickness>");
sb.AppendLine();

// Text styles from tokens.type. Letter spacing (em) becomes CharacterSpacing (1/1000 em); line height is size x ratio.
// "transform": "uppercase" cannot be expressed in a style: callers upper-case label text themselves.
sb.AppendLine("  <!-- Text styles (tokens.type): BrandText<Name>Style -->");
string FontKey(string family, int weight) => (family, weight) switch
{
    ("display", >= 700) => "BrandFontDisplayBold",
    ("display", _) => "BrandFontDisplayMedium",
    ("mono", >= 700) => "BrandFontMonoBold",
    ("mono", _) => "BrandFontMonoMedium",
    ("body", >= 600) => "BrandFontBodySemiBold",
    ("body", >= 500) => "BrandFontBodyMedium",
    _ => "BrandFontBody",
};
foreach (var ty in t.GetProperty("type").EnumerateObject())
{
    var v = ty.Value;
    var size = v.GetProperty("size").GetDouble();
    sb.AppendLine($"  <Style x:Key=\"BrandText{Pascal(ty.Name)}Style\" TargetType=\"TextBlock\">");
    sb.AppendLine($"    <Setter Property=\"FontFamily\" Value=\"{{StaticResource {FontKey(v.GetProperty("family").GetString()!, v.GetProperty("weight").GetInt32())}}}\" />");
    sb.AppendLine($"    <Setter Property=\"FontSize\" Value=\"{Num(size)}\" />");
    if (v.TryGetProperty("letterSpacing", out var ls))
        sb.AppendLine($"    <Setter Property=\"CharacterSpacing\" Value=\"{Num(Math.Round(ls.GetDouble() * 1000))}\" />");
    if (v.TryGetProperty("lineHeight", out var lh))
    {
        sb.AppendLine($"    <Setter Property=\"LineHeight\" Value=\"{Num(Math.Round(size * lh.GetDouble(), 2))}\" />");
        sb.AppendLine("    <Setter Property=\"LineStackingStrategy\" Value=\"BlockLineHeight\" />");
    }
    sb.AppendLine("    <Setter Property=\"Foreground\" Value=\"{ThemeResource BrandTextBrush}\" />");
    sb.AppendLine("    <Setter Property=\"TextWrapping\" Value=\"Wrap\" />");
    sb.AppendLine("  </Style>");
}
sb.AppendLine("</ResourceDictionary>");

Directory.CreateDirectory(Path.GetDirectoryName(outPath)!);
File.WriteAllText(outPath, sb.ToString().Replace("\r\n", "\n"));
Console.WriteLine($"Wrote {Path.GetRelativePath(root, outPath)}");
